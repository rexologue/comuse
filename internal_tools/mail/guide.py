from common.tools.guides import domain_guide


domain_guide(
    "mail",
    agent="""
Пометить письмо прочитанным или переложить его, если это часть ответа на письмо, делай только после
подтверждения отправки: при отказе письмо должно остаться необработанным.""",
    compiler="""
Письмо, которое в разговоре отправлялось, отправляй шагом mail.send (не mail.create_draft), даже если
ассистент в разговоре спрашивал «отправить?»: задача никого ни о чём не спрашивает, а сохранить письмо в
черновики или отправить сразу — решает mail.send по настройкам задачи, которые выбирает пользователь.

Задача, которая разбирает новые письма, берёт их mail.search с not_labeled: [своя метка] и после обработки
ставит эту метку шагом mail.mark add_labels — а не seen: «прочитано» принадлежит пользователю, а письмо,
которое он прочитал раньше задачи, она бы пропустила. Метка — латиницей и по делу задачи (invoices_forwarded,
reports_saved), не общее processed: другая задача по тому же ящику с той же меткой пропустила бы эти письма. mail.read в такой задаче — с тем же sender_in, что у mail.search.

Так же — задача, которая отвечает на письма или пересылает их: метка после ответа, а не answered=false в
поиске. По умолчанию задача кладёт ответ в черновики, а черновик письмо отвеченным не делает: без метки каждый
запуск писал бы новый черновик на те же письма. Тему ответа «Re: …» не составляй сам: mail.send с in_reply_to
добавит «Re:» к теме исходного письма.""",
)
