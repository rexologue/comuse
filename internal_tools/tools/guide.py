from common.tools.guides import domain_guide


domain_guide(
    "tools",
    agent="""
Свою команду (группа.действие, например telegram.send; группа своя, не встроенная) пиши, когда встроенных не хватает и задача повторится: разобрать особый формат,
посчитать то, чего не умеют встроенные команды. Команды одной группы — один плагин: одобряют его целиком. Порядок:
1) tools.list — нет ли уже такой; доработать существующую — сначала tools.show;
2) tools.draft: main.py с def run(args, ctx), который возвращает dict по output_schema. Аргументы — args[...];
путь в рабочей папке объяви в input_schema как {"type": "string", "x-path": "path"} — придёт полный путь.
Файлы результата — только через ctx.output_path("имя"); ошибка для пользователя — raise ToolError("…")
(from agent_tool import ToolError). Пакеты — в requirements, только из PyPI. Внутри нет LLM, почты и аккаунтов:
это обычная функция над данными;
3) tools.try на настоящем файле пользователя; ошибка — исправь черновик (tools.draft) и попробуй снова;
4) когда работает — скажи, что черновик готов: пользователь посмотрит код, пакеты и команды плагина в карточке и одобрит сам.
Одобрить за него нельзя; до одобрения новой команды в каталоге нет, а задачи с командами плагина после одобрения ждут решения пользователя.""",
)
