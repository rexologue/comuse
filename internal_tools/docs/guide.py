from common.tools.guides import domain_guide


domain_guide(
    "docs",
    agent="""
Отчёт «такой же, как пример»:
1) найди файл-пример и файлы с данными за нужный период;
2) прочитай пример (docs.read) и сам реши, что в нём меняется от раза к разу: поля — точные фрагменты текста
(даты, суммы, имена, тема), таблицы — «Таблица T1»… с данными, строки которых будут другими (сколько строк
шапки, ключи колонок). Постоянные заголовки и подписи не размечай;
3) вызови docs.make_template с этой разметкой. Он спросит подтверждения — опиши пользователю разметку простыми
словами: поля (имя — фрагмент из примера) и таблицы (номер, шапка, колонки). Он ответит «да» или поправит
(«колонок всегда 5», «дата постоянная») — тогда вызови docs.make_template заново с исправленной разметкой;
4) числа и текст для шаблона собери командами других групп (суммы — инструментом для таблиц, не в уме);
5) период отчёта бери из дат периода, а не из дат файлов;
6) docs.fill_template с этим шаблоном: ключи context — как в example_context;
7) сообщи пользователю итог и путь к готовому файлу.
Если docs.make_template ответил, что разметка не подходит, исправь названные места, а не всё заново.""",
    compiler="""
Если в разговоре шаблон уже создан (docs.make_template), не создавай его заново — используй готовый путь data:templates/….
Если задача сама делает шаблон, разметку для docs.make_template даёт предыдущий шаг llm.extract: схема результата —
fields и tables, как в аргументах docs.make_template.
Ключи context в docs.fill_template — ровно поля шаблона (fields и tables из docs.make_template).""",
)
